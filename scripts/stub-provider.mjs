/**
 * Local OpenAI-compatible development server (like Ollama).
 * Real HTTP + real SSE through the full UNO Router pipeline — used for
 * development and integration testing without upstream API keys.
 *
 * Usage: node scripts/stub-provider.mjs  (listens on :5050)
 */
import { createServer } from "node:http";

const PORT = Number(process.env.STUB_PORT || 5050);
const MODELS = ["local/uno-test-8b", "local/uno-test-mini"];

function buildReply(messages) {
  const last = [...messages].reverse().find((m) => m.role === "user");
  const text = typeof last?.content === "string" ? last.content : "";
  return [
    `I received your message: "${text.slice(0, 200)}".`,
    "",
    "This response was generated by the UNO local development provider.",
    "Streaming, usage metering, queueing, routing and billing all ran through the real UNO Router pipeline.",
  ].join("\n");
}

function countTokens(text) {
  return Math.max(1, Math.ceil(text.length / 4));
}

function cors(res) {
  res.setHeader("access-control-allow-origin", "*");
  res.setHeader("access-control-allow-headers", "*");
  res.setHeader("access-control-allow-methods", "*");
}

const server = createServer((req, res) => {
  cors(res);
  if (req.method === "OPTIONS") { res.writeHead(204); res.end(); return; }
  if (req.method === "GET" && (req.url === "/v1/models" || req.url === "/models")) {
    res.writeHead(200, { "content-type": "application/json" });
    res.end(JSON.stringify({ object: "list", data: MODELS.map((id) => ({ id, object: "model", created: 1735689600, owned_by: "uno-local" })) }));
    return;
  }
  if (req.method === "POST" && req.url?.startsWith("/v1/chat/completions")) {
    let raw = "";
    req.on("data", (c) => (raw += c));
    req.on("end", () => {
      let body;
      try { body = JSON.parse(raw); } catch {
        res.writeHead(400, { "content-type": "application/json" });
        res.end(JSON.stringify({ error: { message: "invalid JSON" } }));
        return;
      }
      const reply = buildReply(body.messages ?? []);
      const promptTokens = countTokens((body.messages ?? []).map((m) => (typeof m.content === "string" ? m.content : "")).join(""));
      const completionTokens = countTokens(reply);
      const usage = { prompt_tokens: promptTokens, completion_tokens: completionTokens, total_tokens: promptTokens + completionTokens };
      const id = `chatcmpl-local-${Date.now().toString(36)}`;
      const created = Math.floor(Date.now() / 1000);
      const model = body.model || MODELS[0];

      if (body.stream) {
        res.writeHead(200, { "content-type": "text/event-stream", "cache-control": "no-cache", connection: "keep-alive" });
        const base = { id, object: "chat.completion.chunk", created, model };
        res.write(`data: ${JSON.stringify({ ...base, choices: [{ index: 0, delta: { role: "assistant", content: "" }, finish_reason: null }] })}\n\n`);
        const words = reply.split(/(?<=\s)/);
        let i = 0;
        const interval = setInterval(() => {
          if (i >= words.length) {
            clearInterval(interval);
            res.write(`data: ${JSON.stringify({ ...base, choices: [{ index: 0, delta: {}, finish_reason: "stop" }] })}\n\n`);
            res.write(`data: ${JSON.stringify({ ...base, choices: [], usage })}\n\n`);
            res.write("data: [DONE]\n\n");
            res.end();
            return;
          }
          res.write(`data: ${JSON.stringify({ ...base, choices: [{ index: 0, delta: { content: words[i++] }, finish_reason: null }] })}\n\n`);
        }, 25);
        // NOTE: req "close" fires when the request body completes on modern
        // Node — watch the RESPONSE/socket instead so the stream can finish.
        res.on("close", () => clearInterval(interval));
        return;
      }

      res.writeHead(200, { "content-type": "application/json" });
      res.end(JSON.stringify({
        id, object: "chat.completion", created, model,
        choices: [{ index: 0, message: { role: "assistant", content: reply }, finish_reason: "stop" }],
        usage,
      }));
    });
    return;
  }
  res.writeHead(404, { "content-type": "application/json" });
  res.end(JSON.stringify({ error: { message: "not found" } }));
});

server.listen(PORT, () => console.log(`[uno-stub] Local OpenAI-compatible provider listening on http://localhost:${PORT}/v1`));